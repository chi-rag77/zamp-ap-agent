import './load-env';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
import sharp from 'sharp';
import {createServerClient} from '@zamp/database';
import {processEmailMessage} from '@zamp/email';
process.env.AI_PROVIDER='mock';
const source=await readFile(join(process.cwd(),'tests/fixtures/phase03-real-invoice.png'));
const stamp=Date.now();
const metadata=await sharp(source).metadata();
if(!metadata.width||!metadata.height)throw new Error('Fixture image has no dimensions');
const overlay=Buffer.from(`<svg width="${metadata.width}" height="24"><rect width="${metadata.width}" height="24" fill="white"/><text x="5" y="17" font-size="12" fill="black">Phase 6 fixture ${stamp}</text></svg>`);
const file=await sharp(source).composite([{input:overlay,top:metadata.height-24,left:0}]).png().toBuffer();
const messageId=`phase6-smoke-${stamp}`;
const raw={id:messageId,threadId:messageId,historyId:String(stamp),internalDate:String(stamp),payload:{mimeType:'multipart/mixed',headers:[{name:'From',value:'billing@fixture.example'},{name:'To',value:'ap@fixture.example'},{name:'Subject',value:'Invoice fixture'}],parts:[{partId:'1',filename:'invoice-fixture.png',mimeType:'image/png',body:{attachmentId:'fixture-image',size:file.length,data:file.toString('base64url')}}]}};
const result=await processEmailMessage(messageId,{raw,provider:'DEMO'});
const db=createServerClient();
const {data:attachment,error:attachmentError}=await db.from('email_attachments').select('invoice_id,document_status,agent_run_id').eq('email_intake_id',result.emailIntakeId).single();
if(attachmentError)throw attachmentError;
const {data:invoice,error:invoiceError}=await db.from('invoices').select('id,current_extraction_id,status').eq('id',attachment.invoice_id).single();
if(invoiceError)throw invoiceError;
const {data:agent,error:agentError}=await db.from('agent_runs').select('current_state,verification_status').eq('id',attachment.agent_run_id).single();
if(agentError)throw agentError;
const verified=result.status==='PROCESSED'&&result.invoicesCreated===1&&result.agentRunsTriggered===1&&attachment.document_status==='STORED'&&Boolean(invoice.current_extraction_id)&&agent.verification_status==='VERIFIED';
console.log(JSON.stringify({messageId,status:result.status,invoiceId:invoice.id,invoiceStatus:invoice.status,agentState:agent.current_state,verified}));
if(!verified)process.exitCode=1;
